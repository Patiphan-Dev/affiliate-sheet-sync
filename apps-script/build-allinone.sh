#!/usr/bin/env bash
# Regenerate AllInOne.gs from the separate .gs files (run after editing any of them).
# Each file's leading /** … */ doc comment is dropped; everything else is copied as is.
set -euo pipefail
cd "$(dirname "$0")"

# Order matters only for readability — Apps Script loads all .gs into one scope.
FILES=(Config SheetLib Gemini Sanitize WebApp Admin Captions Reviews FbPage Triggers)
BAR='// ═══════════════════════════════════════════════════════════════════════'

{
  cat <<'EOF'
/**
 * AllInOne.gs — every .gs file for Affiliate Sheet Sync concatenated into one,
 * so it can be pasted into a blank Apps Script project in a single step.
 * (Apps Script puts all .gs files in one shared scope anyway.)
 * Still add Admin.html separately (➕ → HTML → name it "Admin").
 * GENERATED by build-allinone.sh — edit the separate .gs files, not this one.
 */

EOF
  for f in "${FILES[@]}"; do
    printf '%s\n// %s.gs\n%s\n' "$BAR" "$f" "$BAR"
    awk 'NR==1 && /^\/\*\*/ {skip=1} skip { if (/\*\//) {skip=0; drop=1} next }
         drop && /^$/ {drop=0; next} {drop=0; print}' "$f.gs"
    printf '\n\n'
  done
} > AllInOne.gs

echo "AllInOne.gs rebuilt from ${#FILES[@]} files"
