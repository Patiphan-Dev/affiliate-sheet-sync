const FALLBACK = CATEGORIES[CATEGORIES.length - 1];

export function categoryFor(name: string): Category {
  const n = name.toLowerCase();
  for (const c of CATEGORIES) {
    if (c.match.some((kw) => n.includes(kw))) return c;
  }
  return FALLBACK;
}

export function getCategory(slug: string): Category | undefined {
  return CATEGORIES.find((c) => c.slug === slug);
}

export function productsInCategory(products: Product[], slug: string): Product[] {
  return products.filter((p) => p.categorySlug === slug);
}
